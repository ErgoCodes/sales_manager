// Prepares an isolated stack for the Playwright suite: a fresh database, migrations, the demo seed,
// throwaway signing secrets, and a production build of the web app. Everything the specs and
// playwright.config.ts need is written to e2e/.runtime/env.json (gitignored).
//
// Needs a Postgres superuser URL in E2E_PG_ADMIN_URL (default: a local container on port 55432). It only
// touches the database named by E2E_DB_NAME (default monaco_e2e), which it drops and recreates.
import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import pg from 'pg';

const webDir = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const repoRoot = resolve(webDir, '../..');
const apiDist = resolve(repoRoot, 'apps/api/dist');
const require = createRequire(import.meta.url);

const adminUrl = new URL(process.env.E2E_PG_ADMIN_URL ?? 'postgres://postgres:postgres@127.0.0.1:55432/postgres');
const dbName = process.env.E2E_DB_NAME ?? 'monaco_e2e';
// This script DROPs the database and (re)applies init.sql, which alters the cluster-wide monaco_* roles.
// So it only accepts a dedicated "*_e2e" database on a loopback server, unless a remote one is opted in.
if (!/^[a-z0-9_]*_e2e$/.test(dbName)) {
  throw new Error(`Refusing E2E_DB_NAME "${dbName}": it must be a dedicated database whose name ends in "_e2e" (lowercase letters, digits, "_").`);
}
const LOOPBACK = new Set(['localhost', '127.0.0.1', '[::1]', '::1']);
if (!LOOPBACK.has(adminUrl.hostname) && process.env.E2E_ALLOW_REMOTE_PG !== '1') {
  throw new Error(`Refusing E2E_PG_ADMIN_URL host "${adminUrl.hostname}": the e2e database is dropped and recreated, so only localhost, 127.0.0.1 or ::1 are accepted. Set E2E_ALLOW_REMOTE_PG=1 to opt in to a disposable remote server.`);
}
const apiPort = process.env.E2E_API_PORT ?? '4180';
const webPort = process.env.E2E_WEB_PORT ?? '3180';

const roleUrl = (role) => {
  const url = new URL(adminUrl);
  url.username = role;
  url.password = role; // development roles from infra/postgres/init.sql
  url.pathname = `/${dbName}`;
  return url.toString();
};
const env = {
  ...process.env,
  NODE_ENV: 'development',
  DATABASE_URL: roleUrl('monaco_app'),
  DATABASE_MIGRATION_URL: roleUrl('monaco_owner'),
};

function run(cmd, args, extraEnv = {}) {
  execFileSync(cmd, args, { cwd: repoRoot, stdio: 'inherit', env: { ...env, ...extraEnv } });
}

// 1. Fresh database with the roles of infra/postgres/init.sql.
const admin = new pg.Client({ connectionString: adminUrl.toString() });
await admin.connect();
try {
  await admin.query(`DROP DATABASE IF EXISTS ${dbName} WITH (FORCE)`);
  await admin.query(`CREATE DATABASE ${dbName}`);
} finally {
  await admin.end();
}
const initClient = new pg.Client({ connectionString: new URL(`/${dbName}`, adminUrl).toString() });
await initClient.connect();
try {
  await initClient.query(readFileSync(resolve(repoRoot, 'infra/postgres/init.sql'), 'utf8'));
} finally {
  await initClient.end();
}

// 2. Schema + demo seed (db:seed builds the API, so dist/ exists afterwards).
run('pnpm', ['--filter', 'api', 'db:migrate']);
run('pnpm', ['--filter', 'api', 'db:seed']);

// 3. Throwaway secrets, generated by the project's own script. Never written outside e2e/.runtime.
const keys = execFileSync('node', [resolve(apiDist, 'scripts/generate-keys.js')], { encoding: 'utf8' });
const jwtPrivateJwk = /^JWT_PRIVATE_JWK='(.+)'$/m.exec(keys)?.[1];
const clientIpHmacSecret = /^CLIENT_IP_HMAC_SECRET=(.+)$/m.exec(keys)?.[1];
if (!jwtPrivateJwk || !clientIpHmacSecret) throw new Error('Could not read the generated secrets from keys:generate');

// 4. Demo credentials come from the seed module itself: the only source of truth.
const { DEMO_USERS } = require(resolve(apiDist, 'scripts/demo-seed.js'));

// 5. Production build of the web app (what `next start` serves in the suite).
const webOrigin = `http://localhost:${webPort}`;
const apiUrl = `http://127.0.0.1:${apiPort}`;
run('pnpm', ['--filter', 'web', 'build'], { API_URL: apiUrl, NODE_ENV: 'production' });

mkdirSync(resolve(webDir, 'e2e/.runtime'), { recursive: true });
writeFileSync(
  resolve(webDir, 'e2e/.runtime/env.json'),
  JSON.stringify({ apiPort, webPort, apiUrl, webOrigin, databaseUrl: env.DATABASE_URL, jwtPrivateJwk, clientIpHmacSecret, demoUsers: DEMO_USERS }, null, 2),
  { mode: 0o600 },
);
console.log(`e2e stack prepared: database ${dbName}, API ${apiUrl}, web ${webOrigin}`);
