import { fireEvent, screen, waitFor } from '@testing-library/dom';
import { describe, expect, it, vi } from 'vitest';

import { act, renderWithReact } from '../../../../../vitest.render';
import type { InventoryActionState } from '@/lib/inventory/document-form';
import { ReverseDocument } from '../movimientos/[id]/reverse-document';

const DOC = '018f0000-0000-7000-8000-0000000000d1';
const R = '018f0000-0000-7000-8000-0000000000d2';
const P1 = '018f0000-0000-7000-8000-000000000001';
type Action = (prev: InventoryActionState, formData: FormData) => Promise<InventoryActionState>;

const click = (name: string) => act(() => void fireEvent.click(screen.getByRole('button', { name })));
const render = (action: Action) => renderWithReact(<ReverseDocument documentId={DOC} reversalId={R} products={[{ id: P1, name: 'Arroz', unitOfMeasure: 'kg' }]} action={action} />);
const confirm = () => act(async () => void fireEvent.submit(document.querySelector('form')!));

describe('ReverseDocument', () => {
  it('asks for confirmation first, and cancelling sends nothing', () => {
    const action = vi.fn<Action>(async () => ({}));
    const { unmount } = render(action);
    expect(screen.queryByRole('button', { name: 'Confirmar reversión' })).toBeNull();
    click('Revertir');
    expect(screen.getByText(/movimientos opuestos/)).toBeInTheDocument();
    expect(screen.getByLabelText('Notas (opcional)')).toBeInTheDocument();
    click('Cancelar');
    expect(screen.queryByRole('button', { name: 'Confirmar reversión' })).toBeNull();
    expect(screen.getByRole('button', { name: 'Revertir' })).toBeInTheDocument();
    expect(action).not.toHaveBeenCalled();
    unmount();
  });

  it('confirming sends the reversal id generated by the page, the same on a double confirm', async () => {
    const action = vi.fn<Action>(async () => ({}));
    const { unmount } = render(action);
    click('Revertir');
    act(() => void fireEvent.change(screen.getByLabelText('Notas (opcional)'), { target: { value: 'carga duplicada' } }));
    await act(async () => {
      const form = document.querySelector('form')!;
      fireEvent.submit(form);
      fireEvent.submit(form);
    });
    await waitFor(() => expect(action).toHaveBeenCalledTimes(2));
    expect(action.mock.calls.map(([, data]) => [data.get('id'), data.get('documentId'), data.get('notes')])).toEqual([
      [R, DOC, 'carga duplicada'],
      [R, DOC, 'carga duplicada'],
    ]);
    unmount();
  });

  it('shows ALREADY_REVERSED and shortages as an alert, keeping the confirmation and the id', async () => {
    const action = vi
      .fn<Action>()
      .mockResolvedValueOnce({ error: 'El documento ya fue revertido o es una reversión: un documento solo se revierte una vez.' })
      .mockResolvedValueOnce({ error: 'No hay stock suficiente para registrar el documento.', shortages: [{ productId: P1, available: 0, shortBy: 2 }] });
    const { unmount } = render(action);
    click('Revertir');
    await confirm();
    expect(await screen.findByRole('alert')).toHaveTextContent('ya fue revertido');
    await confirm();
    await waitFor(() => expect(screen.getByRole('alert')).toHaveTextContent(/Arroz: disponible 0 kg, faltan 2 kg/));
    expect(action.mock.calls.map(([, data]) => data.get('id'))).toEqual([R, R]);
    unmount();
  });
});
