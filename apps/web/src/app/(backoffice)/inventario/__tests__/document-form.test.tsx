import { fireEvent, screen, waitFor } from '@testing-library/dom';
import { renderToStaticMarkup } from 'react-dom/server';
import { describe, expect, it, vi } from 'vitest';

import { act, renderWithReact } from '../../../../../vitest.render';
import type { InventoryActionState, ProductOption } from '@/lib/inventory/document-form';
import { InventoryDocumentForm } from '../document-form';

vi.mock('next/link', () => ({ default: ({ href, children }: { href: string; children: React.ReactNode }) => <a href={href}>{children}</a> }));

const ID = '018f0000-0000-7000-8000-0000000000d1';
const L = '018f0000-0000-7000-8000-0000000000b1';
const P1 = '018f0000-0000-7000-8000-000000000001';
const P2 = '018f0000-0000-7000-8000-000000000002';
const products: ProductOption[] = [
  { id: P1, name: 'Arroz', unitOfMeasure: 'kg', currency: 'CUP', quantity: 10, archived: false },
  { id: P2, name: 'Refresco', unitOfMeasure: 'ud', currency: 'CUP', quantity: 0, archived: false },
];
type Action = (prev: InventoryActionState, formData: FormData) => Promise<InventoryActionState>;

const field = (label: string) => screen.getByLabelText(label) as HTMLInputElement | HTMLSelectElement;
const change = (label: string, value: string) => act(() => void fireEvent.change(field(label), { target: { value } }));
const click = (name: string) => act(() => void fireEvent.click(screen.getByRole('button', { name })));
const render = (kind: 'entry' | 'exit' | 'adjustment', action: Action = vi.fn(async () => ({}))) =>
  renderWithReact(<InventoryDocumentForm kind={kind} documentId={ID} locationId={L} products={products} today="2026-11-21" action={action} cancelHref="/inventario" />);
const submit = () => act(async () => void fireEvent.submit(document.querySelector('form')!));

describe('InventoryDocumentForm', () => {
  it('renders the document id generated by the page as a hidden field, with the location', () => {
    const html = renderToStaticMarkup(<InventoryDocumentForm kind="entry" documentId={ID} locationId={L} products={products} today="2026-11-21" action={vi.fn()} cancelHref="/inventario" />);
    expect(html).toContain(`type="hidden" name="id" value="${ID}"`);
    expect(html).toContain(`name="locationId" value="${L}"`);
    expect(html).toContain('max="2026-11-21"');
  });

  it('adds and removes lines, never below one', () => {
    const { unmount } = render('exit');
    expect(screen.getByRole('button', { name: 'Quitar línea 1' })).toBeDisabled();
    click('Agregar línea');
    expect(field('Producto (línea 2)')).toBeInTheDocument();
    change('Cantidad (línea 2)', '3');
    click('Agregar línea');
    click('Quitar línea 2');
    expect(screen.queryByLabelText('Producto (línea 3)')).toBeNull();
    expect((field('Cantidad (línea 2)') as HTMLInputElement).value).toBe('');
    expect(screen.getByRole('button', { name: 'Quitar línea 1' })).toBeEnabled();
    unmount();
  });

  it('shows the unit cost only on entries', () => {
    const entry = render('entry');
    expect(field('Costo unitario (línea 1)')).toBeInTheDocument();
    entry.unmount();
    const exit = render('exit');
    expect(screen.queryByLabelText('Costo unitario (línea 1)')).toBeNull();
    expect(field('Motivo')).toBeInTheDocument();
    exit.unmount();
  });

  it('validates as the user types: positive quantity, repeated product, future date', () => {
    const { unmount } = render('exit');
    change('Cantidad (línea 1)', '0');
    expect(screen.getByText(/mayor que 0/)).toBeInTheDocument();
    expect(field('Cantidad (línea 1)')).toHaveAttribute('aria-invalid', 'true');
    change('Cantidad (línea 1)', '-2');
    expect(screen.getByText(/mayor que 0/)).toBeInTheDocument();
    change('Producto (línea 1)', P1);
    click('Agregar línea');
    change('Producto (línea 2)', P1);
    expect(screen.getByText(/otra línea/)).toBeInTheDocument();
    change('Fecha', '2026-11-22');
    expect(screen.getByText(/no puede ser futura/)).toBeInTheDocument();
    unmount();
  });

  it('does not submit an invalid form and reveals every error', async () => {
    const action = vi.fn(async () => ({}));
    const { unmount } = render('entry', action);
    await submit();
    expect(action).not.toHaveBeenCalled();
    expect(screen.getByText('Elige un producto.')).toBeInTheDocument();
    expect(screen.getByText(/costo unitario/)).toBeInTheDocument();
    unmount();
  });

  it('a double submit sends the same document id twice, so the API records one document', async () => {
    const action = vi.fn<Action>(async () => ({}));
    const { unmount } = render('exit', action);
    change('Producto (línea 1)', P1);
    change('Cantidad (línea 1)', '2');
    change('Motivo', 'shrinkage');
    await act(async () => {
      const form = document.querySelector('form')!;
      fireEvent.submit(form);
      fireEvent.submit(form);
    });
    await waitFor(() => expect(action).toHaveBeenCalledTimes(2));
    const ids = action.mock.calls.map(([, data]) => data.get('id'));
    expect(ids).toEqual([ID, ID]);
    expect(action.mock.calls[0]![1].getAll('line-productId')).toEqual([P1]);
    unmount();
  });

  it('keeps the same id when resubmitting after an error, and lists shortages by product name', async () => {
    const action = vi.fn<Action>(async () => ({ error: 'No hay stock suficiente para registrar el documento.', shortages: [{ productId: P1, available: 1, shortBy: 1 }] }));
    const { unmount } = render('exit', action);
    change('Producto (línea 1)', P1);
    change('Cantidad (línea 1)', '2');
    change('Motivo', 'owner_withdrawal');
    await submit();
    expect(await screen.findByRole('alert')).toHaveTextContent('No hay stock suficiente');
    expect(screen.getByRole('alert')).toHaveTextContent(/Arroz: disponible 1 kg, faltan 1 kg/);
    change('Cantidad (línea 1)', '1');
    await submit();
    await waitFor(() => expect(action).toHaveBeenCalledTimes(2));
    expect(action.mock.calls.map(([, data]) => data.get('id'))).toEqual([ID, ID]);
    unmount();
  });

  it('accepts a negative adjustment', async () => {
    const action = vi.fn<Action>(async () => ({}));
    const { unmount } = render('adjustment', action);
    change('Producto (línea 1)', P2);
    change('Cantidad (línea 1)', '-1.5');
    await submit();
    await waitFor(() => expect(action).toHaveBeenCalledTimes(1));
    expect(action.mock.calls[0]![1].get('line-quantity')).toBe('-1.5');
    unmount();
  });
});
