'use client';

import Link from 'next/link';
import { useActionState, useId, useState, type FormEvent } from 'react';
import { EXIT_REASONS, MAX_DOCUMENT_LINES, MAX_NOTES_LENGTH } from '@monaco/contracts';
import { Button } from '@/components/ui/button';
import { Input } from '@/components/ui/input';
import { emptyLine, validateDocumentForm, type DocumentFormKind, type DocumentLineValues, type InventoryActionState, type ProductOption, type Shortage } from '@/lib/inventory/document-form';
import { EXIT_REASON_LABELS, formatQuantity } from '@/lib/inventory/format';
import { FormField, SELECT_CLASS, errorProps } from '../catalogo/form-field';

type Action = (prev: InventoryActionState, formData: FormData) => Promise<InventoryActionState>;

interface Props {
  kind: DocumentFormKind;
  /** Generated by the page when it renders: every (re)submit of this form carries it, so the API records one document. */
  documentId: string;
  /** The only location of the document, or the origin of a transfer. */
  locationId: string;
  /** Transfers only: locations the stock may go to (`inventory:transfer` there, D7); the origin is left out. */
  destinations?: readonly LocationOption[];
  products: readonly ProductOption[];
  /** `YYYY-MM-DD` of the server, the latest business date allowed (D13). */
  today: string;
  action: Action;
  cancelHref: string;
}

type Line = DocumentLineValues & { key: number };

export interface LocationOption {
  id: string;
  name: string;
}

/**
 * Lines form for an entry, exit, adjustment or transfer. Validation runs as the user types and again before
 * submitting; an invalid form is never sent. Success redirects (the Server Action), errors stay here.
 */
export function InventoryDocumentForm({ kind, documentId, locationId, destinations = [], products, today, action, cancelHref }: Props) {
  const uid = useId();
  const [state, formAction, pending] = useActionState<InventoryActionState, FormData>(action, {});
  const [lines, setLines] = useState<Line[]>([{ ...emptyLine(), key: 0 }]);
  const [nextKey, setNextKey] = useState(1);
  const [header, setHeader] = useState({ toLocationId: '', reason: '', occurredOn: '', notes: '' });
  const [touched, setTouched] = useState<ReadonlySet<string>>(new Set());
  const [submitted, setSubmitted] = useState(false);

  const byId = new Map(products.map((p) => [p.id, p]));
  const result = validateDocumentForm(kind, { id: documentId, locationId, ...header, lines }, { today, currencyOf: (id) => byId.get(id)?.currency });
  const errors = result.ok ? undefined : result.errors;
  const shown = (key: string, error: string | undefined) => (error && (submitted || touched.has(key)) ? error : undefined);
  const touch = (key: string) => setTouched((cur) => new Set(cur).add(key));

  const updateLine = (index: number, field: keyof DocumentLineValues, value: string) => {
    setLines((cur) => cur.map((line, i) => (i === index ? { ...line, [field]: value } : line)));
    touch(`${lines[index]!.key}-${field}`);
  };
  const addLine = () => {
    setLines((cur) => [...cur, { ...emptyLine(), key: nextKey }]);
    setNextKey((k) => k + 1);
  };
  const removeLine = (index: number) => setLines((cur) => cur.filter((_, i) => i !== index));

  const onSubmit = (event: FormEvent<HTMLFormElement>) => {
    setSubmitted(true);
    if (!result.ok) event.preventDefault();
  };

  const dateId = `${uid}-date`;
  const reasonId = `${uid}-reason`;
  const destinationId = `${uid}-destination`;
  const notesId = `${uid}-notes`;
  const dateError = shown('occurredOn', errors?.occurredOn);
  const reasonError = shown('reason', errors?.reason);
  const destinationError = shown('toLocationId', errors?.toLocationId);
  const notesError = shown('notes', errors?.notes);
  // An archived product admits no entries nor transfers; exits and adjustments can empty its stock.
  const choices = kind === 'entry' || kind === 'transfer' ? products.filter((p) => !p.archived) : products;

  return (
    <form action={formAction} onSubmit={onSubmit} className="space-y-4" noValidate>
      <input type="hidden" name="id" value={documentId} />
      <input type="hidden" name="locationId" value={locationId} />

      <div className="grid gap-3 sm:grid-cols-3">
        {kind === 'transfer' ? (
          <FormField id={destinationId} label="Destino" error={destinationError}>
            <select
              id={destinationId}
              name="toLocationId"
              value={header.toLocationId}
              onChange={(e) => {
                setHeader((h) => ({ ...h, toLocationId: e.target.value }));
                touch('toLocationId');
              }}
              className={SELECT_CLASS}
              {...errorProps(destinationId, destinationError)}
            >
              <option value="">Elige el destino</option>
              {destinations
                .filter((l) => l.id !== locationId)
                .map((l) => (
                  <option key={l.id} value={l.id}>
                    {l.name}
                  </option>
                ))}
            </select>
          </FormField>
        ) : null}
        {kind === 'exit' ? (
          <FormField id={reasonId} label="Motivo" error={reasonError}>
            <select
              id={reasonId}
              name="reason"
              value={header.reason}
              onChange={(e) => {
                setHeader((h) => ({ ...h, reason: e.target.value }));
                touch('reason');
              }}
              className={SELECT_CLASS}
              {...errorProps(reasonId, reasonError)}
            >
              <option value="">Elige un motivo</option>
              {EXIT_REASONS.map((r) => (
                <option key={r} value={r}>
                  {EXIT_REASON_LABELS[r]}
                </option>
              ))}
            </select>
          </FormField>
        ) : null}
        <FormField id={dateId} label="Fecha" hint="Vacía: se registra con la fecha y hora actuales." error={dateError}>
          <Input
            id={dateId}
            name="occurredOn"
            type="date"
            max={today}
            value={header.occurredOn}
            onChange={(e) => {
              setHeader((h) => ({ ...h, occurredOn: e.target.value }));
              touch('occurredOn');
            }}
            {...errorProps(dateId, dateError)}
          />
        </FormField>
        <FormField id={notesId} label="Notas" error={notesError}>
          <Input
            id={notesId}
            name="notes"
            maxLength={MAX_NOTES_LENGTH}
            value={header.notes}
            onChange={(e) => {
              setHeader((h) => ({ ...h, notes: e.target.value }));
              touch('notes');
            }}
            {...errorProps(notesId, notesError)}
          />
        </FormField>
      </div>

      <fieldset className="space-y-2">
        <legend className="text-sm font-medium">Líneas</legend>
        {lines.map((line, index) => {
          const n = index + 1;
          const lineErrors = errors?.lineErrors[index];
          const productError = shown(`${line.key}-productId`, lineErrors?.productId);
          const quantityError = shown(`${line.key}-quantity`, lineErrors?.quantity);
          const costError = shown(`${line.key}-unitCost`, lineErrors?.unitCost);
          const ids = { product: `${uid}-${line.key}-product`, quantity: `${uid}-${line.key}-quantity`, cost: `${uid}-${line.key}-cost` };
          const product = byId.get(line.productId);
          return (
            <div key={line.key} className="grid items-start gap-2 sm:grid-cols-[2fr_1fr_1fr_auto]">
              <div className="space-y-1">
                <select
                  id={ids.product}
                  name="line-productId"
                  aria-label={`Producto (línea ${n})`}
                  value={line.productId}
                  onChange={(e) => updateLine(index, 'productId', e.target.value)}
                  className={SELECT_CLASS}
                  {...errorProps(ids.product, productError)}
                >
                  <option value="">Elige un producto</option>
                  {choices.map((p) => (
                    <option key={p.id} value={p.id}>
                      {p.name} ({formatQuantity(p.quantity)} {p.unitOfMeasure}){p.archived ? ' · archivado' : ''}
                    </option>
                  ))}
                </select>
                <FieldError id={ids.product} error={productError} />
              </div>
              <div className="space-y-1">
                <Input
                  id={ids.quantity}
                  name="line-quantity"
                  aria-label={`Cantidad (línea ${n})`}
                  inputMode="decimal"
                  placeholder={kind === 'adjustment' ? 'Ej.: -2 o 3' : 'Cantidad'}
                  value={line.quantity}
                  onChange={(e) => updateLine(index, 'quantity', e.target.value)}
                  {...errorProps(ids.quantity, quantityError)}
                />
                <FieldError id={ids.quantity} error={quantityError} />
              </div>
              {kind === 'entry' ? (
                <div className="space-y-1">
                  <input type="hidden" name="line-currency" value={product?.currency ?? ''} />
                  <Input
                    id={ids.cost}
                    name="line-unitCost"
                    aria-label={`Costo unitario (línea ${n})`}
                    inputMode="decimal"
                    placeholder={product?.currency ? `Costo en ${product.currency}` : 'Costo unitario'}
                    value={line.unitCost}
                    onChange={(e) => updateLine(index, 'unitCost', e.target.value)}
                    {...errorProps(ids.cost, costError)}
                  />
                  <FieldError id={ids.cost} error={costError} />
                </div>
              ) : (
                <div />
              )}
              <Button type="button" variant="ghost" size="sm" aria-label={`Quitar línea ${n}`} disabled={lines.length === 1} onClick={() => removeLine(index)}>
                Quitar
              </Button>
            </div>
          );
        })}
        {shown('lines', errors?.lines) ? <p className="text-xs text-red-600">{errors?.lines}</p> : null}
        <Button type="button" variant="outline" size="sm" onClick={addLine} disabled={lines.length >= MAX_DOCUMENT_LINES}>
          Agregar línea
        </Button>
      </fieldset>

      {state.error ? (
        <div role="alert" className="rounded-md border border-red-300 bg-red-50 p-3 text-sm text-red-700">
          <p>{state.error}</p>
          {state.shortages?.length ? <ShortageList shortages={state.shortages} products={byId} /> : null}
        </div>
      ) : null}

      <div className="flex gap-2">
        <Button type="submit" disabled={pending}>
          {pending ? 'Guardando…' : 'Guardar'}
        </Button>
        <Button type="button" variant="outline" asChild>
          <Link href={cancelHref}>Cancelar</Link>
        </Button>
      </div>
    </form>
  );
}

function FieldError({ id, error }: { id: string; error: string | undefined }) {
  return error ? (
    <p id={`${id}-error`} className="text-xs text-red-600">
      {error}
    </p>
  ) : null;
}

/** The products of an `INSUFFICIENT_STOCK` answer, by name, with what is available and what is missing. */
export function ShortageList({ shortages, products }: { shortages: readonly Shortage[]; products: ReadonlyMap<string, { name: string; unitOfMeasure: string }> }) {
  return (
    <ul className="mt-1 list-disc pl-5">
      {shortages.map((s) => {
        const product = products.get(s.productId);
        const unit = product ? ` ${product.unitOfMeasure}` : '';
        return (
          <li key={s.productId}>
            {product?.name ?? 'Producto'}
            {s.available !== null && s.shortBy !== null ? `: disponible ${formatQuantity(s.available)}${unit}, faltan ${formatQuantity(s.shortBy)}${unit}` : ''}
          </li>
        );
      })}
    </ul>
  );
}
